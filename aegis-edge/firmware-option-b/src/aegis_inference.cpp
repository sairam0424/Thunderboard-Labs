/*
 * aegis_inference.cpp - Aegis Edge on-device gesture inference (Option B core)
 * ----------------------------------------------------------------------------
 * Target : Silicon Labs Thunderboard Sense 2 (BRD4166A),
 *          EFR32MG12P332F1024GL125, Cortex-M4F @ 38.4 MHz, 256 KB RAM, NO NPU.
 * SDK    : Gecko SDK (GSDK) 4.0.2 + GNU Arm 10-2020-q4-major.
 * Lang   : C++14 (MANDATORY - the Edge Impulse SDK is C++).
 *
 * What this file does (the Option-B sensor->inference->feedback path):
 *   (a) Reads a slice of 3-axis accelerometer data into a buffer via a
 *       get_signal_data callback (EIDSP_OK contract).
 *   (b) Runs the classifier with run_classifier_continuous() to amortize DSP
 *       across slices (run_classifier_init() is called ONCE in init).
 *   (c) Finds the argmax of result.classification[].
 *   (d) Maps the winning gesture to an RGB LED color and drives the LED
 *       (BOARD_rgbledPowerEnable(true) FIRST, then BOARD_rgbledSetColor).
 *   (e) Packs {class_index:uint8, confidence:uint8 0..100} into a 2-byte buffer
 *       and notifies it on the results characteristic, GATED on CCCD subscribe,
 *       via sl_bt_gatt_server_send_notification().
 *
 *   Plus the BLE event handlers: connection_opened -> store handle;
 *   gatt_server_characteristic_status -> track client_config_flags == 2.
 *
 * ============================================================================
 *  BUILD STATUS: *** NOT COMPILED in this environment. ***
 *  No GSDK / ARM toolchain is available here. This is a correct, heavily
 *  commented integration SKELETON. Build it in Simplicity Studio 5 with
 *  GSDK 4.0.2 + GNU Arm 10-2020-q4-major, dropped into your fork of
 *  edgeimpulse/firmware-silabs-thunderboard-sense-2. See ./README.md and
 *  ../integration-notes.md.
 * ============================================================================
 *
 * Legend:
 *   [VERIFIED]          - EI C++ SDK / sl_bt API convention, stable across boards.
 *   [CONFIRM-ON-DEVICE] - board/pin/GSDK/GATT-DB/IMU-specific; validate on HW.
 */

